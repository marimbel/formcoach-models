#!/usr/bin/env python3
"""Write the data tables the report needs (counts per split, class, source and case type) from the files the
pipeline actually produced, so the numbers in the report always match what was trained and tested.

    python scripts/10_data_report.py --data data/processed --gemini data/gemini --out docs/DATA_REPORT.md
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd


def md(df: pd.DataFrame) -> str:
    df = df.copy()
    df.columns = [" / ".join(map(str, c)) if isinstance(c, tuple) else str(c) for c in df.columns]
    cols = [df.index.name or ""] + list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for idx, row in df.iterrows():
        lines.append("| " + " | ".join([str(idx)] + [str(v) for v in row.values]) + " |")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", type=Path, required=True)
    ap.add_argument("--gemini", type=Path)
    ap.add_argument("--out", type=Path, default=Path("docs/DATA_REPORT.md"))
    a = ap.parse_args()

    reps = pd.read_csv(a.data / "reps.csv")
    crops = pd.read_csv(a.data / "crops.csv")
    if "split" not in reps:
        raise SystemExit("run 02_make_splits.py first")
    if "source" not in reps:
        reps["source"] = "own"
        crops["source"] = "own"
    out = ["# Data report (generated by scripts/10_data_report.py; do not edit by hand)", ""]

    out += ["## Model A: form-error classifier", "",
            "One example = one body crop at the bottom of a rep (224×224 RGB). Each rep gives up to 3 crops "
            "(frames around the deepest point); metrics are computed per rep.", ""]
    summ = reps.groupby(["split", "source"]).agg(participants=("participant", "nunique"), videos=("video", "nunique"),
                                                 reps=("rep_id", "count"))
    summ["crops"] = crops.groupby(["split", "source"]).size()
    summ = summ.reindex(["train", "val", "test"], level=0)
    out += ["### Totals by split and source", "", md(summ.reset_index().set_index("split")), ""]
    cls = pd.crosstab(reps.class_name, reps.split).reindex(columns=["train", "val", "test"], fill_value=0)
    cls.loc["TOTAL"] = cls.sum()
    out += ["### Reps per class and split", "", md(cls), ""]
    if "view" in reps:
        out += ["### Camera view (estimated from shoulder width)", "",
                md(pd.crosstab(reps.view, reps.split).reindex(columns=["train", "val", "test"], fill_value=0)), ""]
    leak = set(reps[reps.split == "test"].participant) & set(reps[reps.split != "test"].participant)
    out += ["### Separation check", "",
            f"- Participants in test: {sorted(reps[reps.split == 'test'].participant.unique())}",
            f"- Participants shared between test and train/val: {sorted(leak) or 'none'}",
            f"- Public-data reps in test: {int(((reps.split == 'test') & (reps.source == 'public')).sum())}", ""]

    if a.gemini and (a.gemini / "situations_reviewed.csv").exists():
        sit = pd.read_csv(a.gemini / "situations_reviewed.csv", keep_default_na=False)
        sit["reviewed"] = sit.final_json.str.strip().ne("")
        out += ["## Model B: Gemini coach fine-tuning", "",
                "One example = the evidence for one finished rep (Model A probabilities, joint-angle features, "
                "visibility, camera view, last 3 reps) + the bottom-of-rep crop → a JSON coaching reply.", ""]
        ct = pd.crosstab(sit.case_type, sit.split).reindex(columns=["train", "val", "test"], fill_value=0)
        ct.loc["TOTAL"] = ct.sum()
        out += ["### Situations per case type and split", "", md(ct), ""]
        rv = pd.crosstab(sit.reviewed.map({True: "human-reviewed", False: "unedited draft"}), sit.split)
        out += ["### Reviewed targets", "", md(rv), ""]
        for f in ("train.jsonl", "val.jsonl", "test_eval.jsonl"):
            p = a.gemini / f
            if p.exists():
                out.append(f"- `{f}`: {sum(1 for _ in open(p))} examples")
        out.append("")

    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text("\n".join(out))
    print(f"wrote {a.out}")
    print(json.dumps({"reps": len(reps), "crops": len(crops), "test_participants": int(reps[reps.split == "test"].participant.nunique())}))


if __name__ == "__main__":
    main()
